/** ระดับชั้น → คำแนะนำเรื่องภาษา/ความยาก */
function level_hint(string $grade): string
{
    if (preg_match('/^ป\.([1-3])$/u', $grade)) {
        return 'ผู้เรียนเป็นเด็กเล็ก: ประโยคสั้นมาก คำง่าย ตัวเลขและตัวอย่างอยู่ใกล้ตัวเด็ก';
    }
    if (preg_match('/^ป\.[4-6]$/u', $grade)) {
        return 'ผู้เรียนเป็นเด็กประถมตอนปลาย: ประโยคสั้นกระชับ คำศัพท์เหมาะกับวัย เริ่มมีการคิดวิเคราะห์ง่ายๆ';
    }
    if (preg_match('/^ม\.[1-3]$/u', $grade)) {
        return 'ผู้เรียนเป็นนักเรียนมัธยมต้น: ใช้ศัพท์วิชาการระดับพื้นฐานได้ มีโจทย์ที่ต้องคิดวิเคราะห์ประกอบ';
    }
    return 'ผู้เรียนเป็นนักเรียนมัธยมปลาย: ใช้ศัพท์วิชาการได้ตามระดับ โจทย์เน้นความเข้าใจและการประยุกต์';
}

/** ข้อกำหนดเฉพาะตามวิชา (โปรไฟล์วิชา: ข้อห้าม/ข้อควรระวังด้านข้อเท็จจริง) */
function subject_hint(string $subject): string
{
    $out = [];
    if (str_contains($subject, 'ภาษาอังกฤษ')) {
        $out[] = 'ข้อความโจทย์ คำตอบ และตัวเลือกให้เป็นภาษาอังกฤษที่ถูกต้อง ระดับคำศัพท์/ไวยากรณ์เหมาะกับชั้นและเทียบเคียงระดับ CEFR (ป.1-3 ประมาณ pre-A1/A1, ป.4-6 A1-A2, ม.1-3 A2-B1, ม.4-6 B1-B2) (คำสั่งในใบงาน instruction เขียนเป็นภาษาไทยได้) ห้ามเฉลยที่ถูกได้มากกว่าหนึ่งตัวเลือก ระวังข้อไวยากรณ์ที่ถูกได้หลายแบบตามบริบท';
    }
    if (str_contains($subject, 'ภาษาไทย')) {
        $out[] = 'ใช้ภาษาไทยถูกต้องตามหลักภาษาและการสะกดคำตามราชบัณฑิตยสภา คำตอบต้องตัดสินได้ชัดเจนตามหลักภาษา ข้อเรื่องหลักภาษา (ชนิดของคำ ประโยค พยางค์ คำควบกล้ำ อักษรสามหมู่ วรรณยุกต์) ต้องไม่กำกวม ห้ามแต่งคำประพันธ์ขึ้นแล้วอ้างว่าเป็นของกวีจริง';
    }
    if (preg_match('/คณิต|ฟิสิกส์|เคมี|เศรษฐศาสตร์|วิทยาการคำนวณ/u', $subject)) {
        $out[] = 'ตัวเลขและการคำนวณต้องถูกต้อง ให้คำนวณซ้ำก่อนตอบ ทุกข้อต้องมีคำตอบเดียวที่ถูกต้องและค่าที่ให้ต้องครบพอสำหรับคำนวณ ใช้หน่วยให้ถูกต้องและสอดคล้องกัน';
    }
    if (preg_match('/วิทยาศาสตร์|ชีววิทยา|เคมี|ฟิสิกส์|โลก/u', $subject)) {
        $out[] = 'ข้อเท็จจริงทางวิทยาศาสตร์ต้องตรงตามที่ยอมรับกันทั่วไป ไม่สร้างตัวเลข/สถิติ/ชื่อนักวิทยาศาสตร์ที่ไม่แน่ใจ ใช้คำศัพท์ตามหลักสูตรไทย';
    }
    if (preg_match('/สังคม|ประวัติศาสตร์|ศาสนา|หน้าที่พลเมือง|ภูมิศาสตร์/u', $subject)) {
        $out[] = 'ข้อเท็จจริงทางประวัติศาสตร์/ภูมิศาสตร์/ศาสนา (ชื่อบุคคล ปี พ.ศ. สถานที่ ตัวเลข) ต้องเป็นสิ่งที่แน่ใจเท่านั้น ถ้าไม่แน่ใจให้ถามเชิงแนวคิดแทนการถามตัวเลข/วันที่เฉพาะ และใช้ถ้อยคำเป็นกลางในประเด็นที่มีความเห็นต่าง';
    }
    return implode(' | ', $out);
}

function is_secondary(string $grade): bool
{
    return (bool) preg_match('/^ม\./u', $grade);
}

function system_teacher(string $grade = 'ป.2', string $subject = 'วิทยาศาสตร์', bool $formal = false): string
{
    $extra = subject_hint($subject);
    $base = "คุณเป็นครูชาวไทยผู้สอนวิชา{$subject} ชั้น{$grade} ที่เชี่ยวชาญหลักสูตรแกนกลางการศึกษาขั้นพื้นฐาน (ฉบับปรับปรุง พ.ศ. 2560) ";
    if ($formal) {
        return $base
            . 'ออกแบบเอกสารการสอนแบบทางการเหมือนใบงาน/แบบทดสอบที่ครูมัธยมใช้จริง ใช้ภาษาวิชาการที่ถูกต้อง กระชับ ไม่ใช้ภาษาเด็กหรือคำน่ารัก '
            . level_hint($grade) . ' '
            . 'เนื้อหา ตัวเลข หน่วย และเฉลยต้องถูกต้องตามหลักวิชาการ ให้คำนวณซ้ำก่อนตอบทุกครั้ง '
            . ($extra !== '' ? $extra . ' ' : '')
            . 'เขียนสูตร สัญลักษณ์ ตัวห้อย ยกกำลัง เศษส่วน และหน่วยเป็น LaTeX ใน $...$ เช่น $W = Fs\\cos\\theta$, $2\\times10^{4}\\ \\mathrm{kg\\cdot m/s}$, $v^2 = u^2 + 2as$ '
            . 'ห้ามอ้างว่าโจทย์มาจากข้อสอบจริง (เช่น O-NET, A-Level, PAT, ปีการศึกษาใด) ห้ามใส่เลขใบงานหรือชื่อ-สกุลในเนื้อหา '
            . 'headerImagePrompt ให้เป็น "" เสมอ';
    }
    return $base
        . 'ออกแบบใบงานภาษาไทยที่ผู้เรียนอ่านเข้าใจง่าย ' . level_hint($grade) . ' '
        . 'เนื้อหาต้องถูกต้องตามหลักวิชาการ ห้ามใส่เลขใบงานหรือชื่อ-สกุลในเนื้อหา '
        . ($extra !== '' ? $extra . ' ' : '')
        . 'ส่วน imagePrompt ให้เขียนเป็นภาษาอังกฤษสั้นๆ บรรยายวัตถุเดียวที่วาดเป็นภาพลายเส้นได้ง่าย '
        . 'ห้ามให้มีตัวหนังสือในภาพ และให้เป็น "" ถ้าข้อนั้นไม่เหมาะกับการมีภาพ';
}

