/** $items = [['uid','topic','type','objective'], ...] */
function book_prompt(string $grade, string $subject, string $hint, array $items): string
{
    $lines = [
        "ช่วยออกแบบเล่มรวมใบงานวิชา{$subject} ชั้น{$grade} ประกอบด้วย ชื่อเล่ม ชื่อรอง คำขวัญ คำนำ ภาพปก และการจัดหมวดใบงาน",
        'รายการใบงาน (uid | หัวข้อ | รูปแบบ | จุดประสงค์):',
    ];
    foreach ($items as $it) {
        $lines[] = "- {$it['uid']} | {$it['topic']} | {$it['type']} | {$it['objective']}";
    }
    $lines[] = 'เงื่อนไข:';
    $lines[] = '- chapters ต้องรวมทุก uid ตามรายการข้างต้น ครั้งเดียวพอดี ห้ามแต่ง uid ใหม่';
    $lines[] = '- จัดหมวดตามเนื้อหาที่เกี่ยวข้องกัน รักษาลำดับเดิมของรายการให้มากที่สุด (เรียงง่ายไปยาก) ถ้าใบงานน้อยกว่า 4 ใบ ใช้ 1 หมวดได้';
    $lines[] = '- แต่ละหมวดมีใบงานอย่างน้อย 1 ใบ';
    $lines[] = preg_match('/ม\./u', $grade)
        ? '- ผู้อ่านเป็นนักเรียนมัธยม: ใช้ภาษาทางการแบบหนังสือเรียน/เอกสารประกอบการสอน ไม่ใช้ภาษาเด็กหรือคำน่ารัก ภาพปกเป็นภาพประกอบเชิงวิชาการของเนื้อหา'
        : '- ผู้อ่านเป็นนักเรียนประถม: ภาษาอบอุ่น สนุก เข้าใจง่าย';
    if (trim($hint) !== '') {
        $lines[] = 'ข้อเสนอแนะเพิ่มเติมจากครู: ' . trim($hint);
    }
    return implode("\n", $lines);
}


